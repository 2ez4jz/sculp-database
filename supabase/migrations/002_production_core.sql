-- Only Miranda (owner) and Jz (operations) are global business viewers.
-- Technical/system data is intentionally limited to Jz's operations role.
create or replace function public.is_business_admin() returns boolean
language sql stable security definer set search_path=public
as $$ select coalesce(public.current_app_role() in ('owner','operations'),false) $$;

create or replace function public.is_staff_manager() returns boolean
language sql stable security definer set search_path=public
as $$ select public.is_business_admin() $$;

create or replace function public.is_system_admin() returns boolean
language sql stable security definer set search_path=public
as $$ select coalesce(public.current_app_role()='operations',false) $$;

