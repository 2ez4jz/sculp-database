-- A booking can contain several services. Prices live on immutable line
-- items so historical reporting does not change when the service menu does.
create table public.booking_services (
 id uuid primary key default gen_random_uuid(),
 booking_id uuid not null references public.bookings(id) on delete cascade,
 service_id uuid references public.services(id) on delete restrict,
 description text not null,
 quantity numeric(8,2) not null default 1 check (quantity > 0),
 unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
 discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
 tax_amount numeric(12,2) not null default 0 check (tax_amount >= 0),
 line_total numeric(12,2) generated always as (
   greatest((quantity * unit_price) - discount_amount + tax_amount, 0)
 ) stored,
 position integer not null default 0,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create index booking_services_booking_id_idx on public.booking_services(booking_id);

