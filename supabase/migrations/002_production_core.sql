-- Trusted reporting views. Sculpy reads these totals instead of inventing
-- arithmetic in a language-model response.
create or replace view public.booking_financials
with (security_invoker=true) as
select
 b.id as booking_id,
 b.client_id,
 b.starts_at,
 b.status,
 b.currency,
 coalesce(sum(bs.line_total), b.price_cad, 0)::numeric(12,2) as booked_total,
 coalesce((
   select sum(p.amount)
   from public.invoices i
   join public.payments p on p.invoice_id=i.id
   where i.booking_id=b.id and i.deleted_at is null and p.status='succeeded'
 ),0)::numeric(12,2) as paid_total
from public.bookings b
left join public.booking_services bs on bs.booking_id=b.id
where b.deleted_at is null
group by b.id;

create or replace view public.service_revenue_monthly
with (security_invoker=true) as
select
 date_trunc('month', coalesce(p.paid_at, p.created_at)) as revenue_month,
 bs.service_id,
 s.code as service_code,
 s.name as service_name,
 sum(
   p.amount * case when inv.total_amount > 0 then bs.line_total / inv.total_amount else 0 end
 )::numeric(12,2) as recognized_revenue
from public.payments p
join public.invoices inv on inv.id=p.invoice_id and inv.deleted_at is null
join public.booking_services bs on bs.booking_id=inv.booking_id
left join public.services s on s.id=bs.service_id
where p.status='succeeded'
group by 1,2,3,4;

-- Timestamp and audit helpers ---------------------------------------------

create or replace function public.set_updated_at() returns trigger
language plpgsql set search_path=public
as $$ begin new.updated_at=now(); return new; end $$;

create or replace function public.write_audit_event() returns trigger
language plpgsql security definer set search_path=public
as $$
declare record_json jsonb;
begin
 record_json=case when TG_OP='DELETE' then to_jsonb(old) else to_jsonb(new) end;
 insert into public.audit_events(actor_id,entity_type,entity_id,action,before_value,after_value)
 values (
   auth.uid(), TG_TABLE_NAME,
   coalesce(record_json->>'id',record_json->>'booking_id',record_json->>'client_id')::uuid,
   lower(TG_OP),
   case when TG_OP in ('UPDATE','DELETE') then to_jsonb(old) else null end,
   case when TG_OP in ('INSERT','UPDATE') then to_jsonb(new) else null end
 );
 if TG_OP='DELETE' then return old; end if;
 return new;
end $$;

do $$
declare table_name text;
begin
 foreach table_name in array array[
   'profiles','artists','clients','venues','partners','bookings','work_logs',
   'client_private','services','media','portfolio_items','reminders','ai_drafts','booking_services',
   'artist_compensations','invoices','payments','ai_threads'
 ] loop
   execute format('drop trigger if exists set_%I_updated_at on public.%I',table_name,table_name);
   execute format(
     'create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()',
     table_name, table_name
   );
 end loop;
end $$;

do $$
declare table_name text;
begin
 foreach table_name in array array[
   'clients','client_private','bookings','booking_services','booking_artists',
   'artist_compensations','invoices','payments','client_consents','work_logs','media','portfolio_items'
 ] loop
   execute format('drop trigger if exists audit_%I on public.%I',table_name,table_name);
   execute format(
     'create trigger audit_%I after insert or update or delete on public.%I for each row execute function public.write_audit_event()',
     table_name, table_name
   );
 end loop;
end $$;

