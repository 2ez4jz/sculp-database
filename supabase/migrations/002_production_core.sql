drop policy if exists clients_read_related on public.clients;
create policy clients_read_related on public.clients for select using (
 deleted_at is null and (
   public.is_business_admin() or exists(
     select 1 from public.bookings b
     where b.client_id=clients.id and b.deleted_at is null and public.is_assigned_to_booking(b.id)
   )
 )
);

drop policy if exists bookings_read_assigned on public.bookings;
